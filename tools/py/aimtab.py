#!/usr/bin/env python3
"""Measure and build the host-side X correction table (port/src/aimtab.h, issue #10).

The game's X is 2 x table[H] and the core's light-gun scaling leaves it -2..+4 px from where the
host aimed (docs/gun.md, section 4). The host looks the commanded X up in a table so that the
game's X lands on the mouse.

    aimtab.py sweep OUT.txt        write a port script that commands every x = 0..319 and logs gun_x
    aimtab.py build PEEK.LOG OUT.h turn the log of that script into the table

Measure with the correction off and the fast aim patch on (the steady state is the same as with
the game's own averaging):

    SDL_VIDEODRIVER=dummy SDL_AUDIODRIVER=dummy build/port/t2port --script build/aimsweep.txt \
        --outdir build/aim --mute --options aim_correct=off,aim=fast
    python3 -I tools/py/aimtab.py build build/aim/peek.log port/src/aimtab.h

The sweep loads the level-1 state that port/scripts/menuflow.txt saves, so the table is measured
in gameplay, where it is used.
"""
import re
import sys

PRE = """# generated by tools/py/aimtab.py sweep: commanded x -> game X (gun_x), y fixed
# needs the state l1 that port/scripts/menuflow.txt saves (level 1, reached with the mouse alone)
load l1
mouse 160 112
run 30
"""


def sweep(out):
    lines = [PRE]
    for x in range(320):
        lines.append("mouse %d 112" % x)
        lines.append("run 3")
        lines.append("peek x%d FF9F6E 2" % x)
    open(out, "w").write("\n".join(lines) + "\n")


def build(log, out):
    got = {}
    for ln in open(log):
        m = re.match(r"\d+ x(\d+) ([0-9a-f]+)$", ln.strip())
        if m:
            got[int(m.group(1))] = int(m.group(2), 16)
    if len(got) != 320:
        sys.exit("need 320 samples, got %d" % len(got))
    best = []
    for t in range(320):
        # the commanded x whose game X is nearest the target; ties: the smaller command error
        c = min(range(320), key=lambda c: (abs(got[c] - t), abs(c - t)))
        best.append(c)
    errs = [got[best[t]] - t for t in range(320)]
    raw = [got[t] - t for t in range(320)]
    hist = lambda e: {k: e.count(k) for k in sorted(set(e))}
    sys.stderr.write("error without table %s\nwith table    %s\n" % (hist(raw), hist(errs)))
    with open(out, "w") as f:
        f.write("/* generated by tools/py/aimtab.py: commanded x that makes the game's X land on the mouse x.\n"
                " * Measured with aim=fast; the game's X is always even. */\n")
        f.write("static const unsigned short aim_cmd_x[320] = {\n")
        for i in range(0, 320, 16):
            f.write("\t" + ", ".join("%d" % v for v in best[i:i + 16]) + ",\n")
        f.write("};\n")


def main():
    a = sys.argv[1:]
    if len(a) >= 2 and a[0] == "sweep":
        sweep(a[1])
    elif len(a) == 3 and a[0] == "build":
        build(a[1], a[2])
    elif len(a) == 2 and a[0] == "identity":
        open(a[1], "w").write("static const unsigned short aim_cmd_x[320] = {\n" +
                              "".join("\t%s,\n" % ", ".join("%d" % v for v in range(i, i + 16)) for i in range(0, 320, 16)) + "};\n")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
