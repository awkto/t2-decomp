#!/usr/bin/env python3
"""Merge runtime indirect-jump targets (harness outdir/ijump.txt) into data/indirect_runtime.txt and
check them against the static resolution.

    ijmerge.py [--dry] IJUMP_OR_DIR...

ijump.txt lines are "site target count" (hex, hex, decimal): a register-indirect jmp/jsr at `site` was
seen jumping to `target`. Arguments are files or directories searched recursively for ijump.txt. The
existing data/indirect_runtime.txt is unioned with them and rewritten as "site target" lines.

Check: every observed target of a site must be among that site's targets in data/indirect.txt or a seed
in tools/py/seeds.txt (the hand-resolved SEEDED sites). Missing ones are printed: they are code the
static pass does not know about (add them to seeds.txt). Targets in RAM ($FF0000+) are listed apart.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "data", "indirect_runtime.txt")


def load(path):
    pairs = set()
    if os.path.exists(path):
        for line in open(path):
            if line.strip() and not line.startswith("#"):
                f = line.split()
                pairs.add((int(f[0], 16), int(f[1], 16)))
    return pairs


def static_targets():
    """site -> targets listed in data/indirect.txt; plus the set of seeds."""
    sites = {}
    for line in open(os.path.join(ROOT, "data", "indirect.txt")):
        if line.startswith("#") or not line.strip():
            continue
        body = line.split(";")[0].split("[")[0].split()
        try:
            site = int(body[0], 16)
        except ValueError:
            continue
        sites[site] = {int(w, 16) for w in body if len(w) == 6 and all(c in "0123456789abcdef" for c in w)} - {site}
    seeds = set()
    for line in open(os.path.join(ROOT, "tools", "py", "seeds.txt")):
        w = line.split("#")[0].split()
        if w:
            seeds.add(int(w[0], 16))
    return sites, seeds


def main(argv):
    dry = "--dry" in argv
    args = [a for a in argv if a != "--dry"]
    files = []
    for a in args:
        if os.path.isdir(a):
            for dp, _, fs in os.walk(a):
                if "ijump.txt" in fs:
                    files.append(os.path.join(dp, "ijump.txt"))
        else:
            files.append(a)
    old = load(OUT)
    new = set(old)
    for f in sorted(files):
        new |= load(f)
    sites = sorted({s for s, _ in new})
    print(f"{len(files)} files, {len(new)} pairs ({len(new - old)} new), {len(sites)} sites", file=sys.stderr)
    st, seeds = static_targets()
    miss = sorted((s, t) for s, t in new if t < 0xFF0000 and t not in st.get(s, set()) and t not in seeds)
    ram = sorted((s, t) for s, t in new if t >= 0xFF0000)
    for s, t in miss:
        print(f"not in the static resolution or seeds: {s:06x} -> {t:06x}")
    for s, t in ram:
        print(f"RAM target: {s:06x} -> {t:06x}")
    print(f"{len(new) - len(miss) - len(ram)} of {len(new)} runtime pairs are covered statically", file=sys.stderr)
    if dry:
        return
    out = ["# Runtime targets of register-indirect jmp/jsr sites (generated by tools/py/ijmerge.py from the",
           "# harness's ijump.txt): site target, hex. Observed in play; checked against data/indirect.txt + seeds."]
    out += [f"{s:06x} {t:06x}" for s, t in sorted(new)]
    open(OUT, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
