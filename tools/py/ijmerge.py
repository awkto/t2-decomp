#!/usr/bin/env python3
"""Merge runtime indirect-jump targets (harness outdir/ijump.txt) into data/indirect_runtime.txt.

    ijmerge.py [--dry] IJUMP_OR_DIR...

ijump.txt lines are "site target count" (hex, hex, decimal): a register-indirect jmp/jsr at `site`
was seen jumping to `target`. Arguments are files or directories searched recursively for
ijump.txt. The existing data/indirect_runtime.txt is unioned with them and rewritten as
"site target" lines; tools/py/indirect.py adds these targets to the statically resolved ones.
Targets in RAM ($FF0000+) are kept, for the record, but are not code seeds.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "data", "indirect_runtime.txt")


def load(path):
    pairs = set()
    if os.path.exists(path):
        for line in open(path):
            if line.strip() and not line.startswith("#"):
                f = line.split()
                pairs.add((int(f[0], 16), int(f[1], 16)))
    return pairs


def main(argv):
    dry = "--dry" in argv
    args = [a for a in argv if a != "--dry"]
    files = []
    for a in args:
        if os.path.isdir(a):
            for dp, _, fs in os.walk(a):
                if "ijump.txt" in fs:
                    files.append(os.path.join(dp, "ijump.txt"))
        else:
            files.append(a)
    old = load(OUT)
    new = set(old)
    for f in sorted(files):
        new |= load(f)
    sites = sorted({s for s, _ in new})
    print(f"{len(files)} files, {len(new)} pairs ({len(new - old)} new), {len(sites)} sites", file=sys.stderr)
    if dry:
        return
    out = ["# Runtime targets of register-indirect jmp/jsr sites (generated by tools/py/ijmerge.py from the",
           "# harness's ijump.txt). site target, hex. Observed in play: complete only for what play reached."]
    out += [f"{s:06x} {t:06x}" for s, t in sorted(new)]
    open(OUT, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
